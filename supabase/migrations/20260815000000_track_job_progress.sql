
alter table public.job_requests
  drop constraint if exists job_requests_status_check;

alter table public.job_requests
  add constraint job_requests_status_check check (
    status in (
      'open',
      'accepted',
      'scheduled',
      'on_the_way',
      'in_progress',
      'pending_completion',
      'completed',
      'closed',
      'cancelled'
    )
  );

create table public.job_status_history (
  id bigint generated by default as identity primary key,
  job_request_id uuid not null references public.job_requests(id) on delete cascade,
  status text not null check (
    status in (
      'accepted',
      'scheduled',
      'on_the_way',
      'in_progress',
      'pending_completion',
      'completed'
    )
  ),
  updated_at timestamptz not null default now(),
  unique (job_request_id, status)
);

create index job_status_history_job_request_id_idx
  on public.job_status_history (job_request_id, updated_at);

alter table public.job_status_history enable row level security;
grant select on public.job_status_history to authenticated;

create policy "Customers can view their job status history"
  on public.job_status_history for select to authenticated
  using (
    exists (
      select 1
      from public.job_requests as job
      where job.id = job_status_history.job_request_id
        and job.customer_id = (select auth.uid())
    )
  );

create or replace function public.record_job_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status is distinct from old.status
    and new.status in (
      'accepted',
      'scheduled',
      'on_the_way',
      'in_progress',
      'pending_completion',
      'completed'
    ) then
    insert into public.job_status_history (job_request_id, status, updated_at)
    values (new.id, new.status, coalesce(new.updated_at, now()))
    on conflict (job_request_id, status) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists job_requests_record_status_change on public.job_requests;
create trigger job_requests_record_status_change
  after update of status on public.job_requests
  for each row execute function public.record_job_status_change();

