drop function if exists public.get_customer_notifications(uuid, integer);
create function public.get_customer_notifications(
  p_customer_id uuid,
  p_limit integer default 20
)
returns table (
  notification_id bigint,
  notification_type text,
  title text,
  message text,
  destination text,
  created_at timestamptz,
  read_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_customer_id <> auth.uid() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;

  return query
  select
    notification.id,
    notification.notification_type,
    notification.title,
    notification.message,
    notification.destination,
    notification.created_at,
    notification.read_at
  from public.customer_notifications as notification
  where notification.customer_id = p_customer_id
  order by notification.created_at desc
  limit least(greatest(coalesce(p_limit, 20), 1), 50);
end;
$$;

drop function if exists public.mark_customer_notifications_read(uuid, bigint[]);
create function public.mark_customer_notifications_read(
  p_customer_id uuid,
  p_notification_ids bigint[] default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_updated_count integer;
begin
  if p_customer_id <> auth.uid() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;

  update public.customer_notifications as notification
  set read_at = now()
  where notification.customer_id = p_customer_id
    and notification.read_at is null
    and (
      p_notification_ids is null
      or notification.id = any(p_notification_ids)
    );

  get diagnostics v_updated_count = row_count;
  return v_updated_count;
end;
$$;

revoke all on function public.get_customer_notifications(uuid, integer) from public;
revoke all on function public.mark_customer_notifications_read(uuid, bigint[]) from public;

grant execute on function public.get_customer_notifications(uuid, integer) to authenticated;
grant execute on function public.mark_customer_notifications_read(uuid, bigint[]) to authenticated;

