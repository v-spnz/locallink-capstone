create table public.customer_notifications (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references auth.users(id) on delete cascade,
  notification_type text not null check (
    notification_type in (
      'new_quote',
      'quote_withdrawn',
      'job_completed'
    )
  ),
  title text not null,
  message text not null,
  destination text not null,
  related_job_request_id uuid references public.job_requests(id) on delete set null,
  related_quote_id uuid references public.job_quotes(id) on delete set null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index customer_notifications_customer_created_idx
  on public.customer_notifications (customer_id, created_at desc);

alter table public.customer_notifications enable row level security;
grant select on public.customer_notifications to authenticated;
grant update (read_at) on public.customer_notifications to authenticated;

create policy "Customers can view their own notifications"
  on public.customer_notifications for select to authenticated
  using (customer_id = (select auth.uid()));

create policy "Customers can mark their own notifications as read"
  on public.customer_notifications for update to authenticated
  using (customer_id = (select auth.uid()))
  with check (customer_id = (select auth.uid()));

  create or replace function public.notify_customer_about_new_quote()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_customer_id uuid;
  v_job_title text;
  v_business_name text;
begin
  select job.customer_id, job.title
    into v_customer_id, v_job_title
  from public.job_requests as job
  where job.id = new.job_request_id;

  select business.business_name
    into v_business_name
  from public.businesses as business
  where business.id = new.business_id;

  insert into public.customer_notifications (
    customer_id,
    notification_type,
    title,
    message,
    destination,
    related_job_request_id,
    related_quote_id
  )
  values (
    v_customer_id,
    'new_quote',
    'New quote received',
    coalesce(v_business_name, 'A provider') || ' sent a quote on ' ||
      coalesce(v_job_title, 'your job') || '.',
    '/jobs',
    new.job_request_id,
    new.id
  );

  return new;
end;
$$;

create trigger job_quotes_notify_customer_new_quote
  after insert on public.job_quotes
  for each row execute function public.notify_customer_about_new_quote();

